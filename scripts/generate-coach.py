"""Offline asset build. See assets/coach/README.md; never used in the browser."""
import argparse
import hashlib
import json
from pathlib import Path

import numpy as np
import soundfile as sf
from kokoro_onnx import Kokoro

parser = argparse.ArgumentParser()
parser.add_argument("--models", type=Path, default=Path(".voice-tools/models"))
parser.add_argument("--limit", type=int, default=0, help="Render a small sample first")
parser.add_argument("--force", action="store_true")
args = parser.parse_args()
root = Path(__file__).resolve().parent.parent
phrases = json.loads((root / "assets/coach/phrases.json").read_text(encoding="utf-8"))
profile = json.loads((root / "assets/coach/profile.json").read_text(encoding="utf-8"))
model = args.models / "kokoro-v1.0.onnx"
voices = args.models / "voices-v1.0.bin"
kokoro = Kokoro(str(model), str(voices))
manifest = {}
for i, phrase in enumerate(phrases[:args.limit or None]):
    path = root / phrase["file"]
    if args.force or not path.exists():
        # Use the selected audition's stock voice and natural speaking speed.
        # Separate count/prompt settings allow timing adjustments if needed.
        speed = (profile["countSpeed"] if phrase["text"].isdigit() else
                 profile["shortCueSpeed"] if len(phrase["spoken"].split()) <= 3 else profile["speed"])
        samples, rate = kokoro.create(phrase["spoken"], voice=profile["voice"], speed=speed, lang=profile["language"])
        # Remove dead air without chopping low-volume consonants. Keep a short
        # fade at both ends to avoid clicks when a count is interrupted.
        audible = np.flatnonzero(np.abs(samples) > 0.003)
        if not len(audible):
            raise ValueError(f"Silent generation: {phrase['text']}")
        pad = int(rate * 0.035)
        samples = samples[max(0, audible[0]-pad):min(len(samples), audible[-1]+pad)]
        fade = min(int(rate * 0.008), len(samples)//2)
        samples[:fade] *= np.linspace(0, 1, fade)
        samples[-fade:] *= np.linspace(1, 0, fade)
        peak = np.max(np.abs(samples))
        samples *= min(2.0, 0.89 / peak)
        sf.write(str(path), samples, rate, format="MP3", bitrate_mode="CONSTANT", compression_level=0.5)
    info = sf.info(str(path))
    manifest[phrase["text"]] = {"file": phrase["file"], "duration": round(info.duration, 3)}
    print(f"{i+1}/{len(phrases)} {info.duration:.2f}s {phrase['text'][:80]}", flush=True)

if not args.limit:
    (root / "assets/coach/manifest.js").write_text(
        "// Generated by scripts/generate-coach.py. Do not hand-edit.\nwindow.COACH_CLIPS = "
        + json.dumps(manifest, ensure_ascii=False, indent=2) + ";\n", encoding="utf-8")
    provenance = {
        "engine": "kokoro-onnx 0.6.1", "model": "Kokoro v1.0", "profile": profile,
        "sampleRate": 24000,
        "sha256": {p.name: hashlib.sha256(p.read_bytes()).hexdigest() for p in [model, voices]}
    }
    (root / "assets/coach/generation.json").write_text(json.dumps(provenance, indent=2) + "\n", encoding="utf-8")
